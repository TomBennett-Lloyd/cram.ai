import { createServer, type IncomingMessage, type Server, type ServerResponse } from 'node:http';
import type { AddressInfo } from 'node:net';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { PROVISIONAL_DEFAULT_PINS } from '../../provisional-pins';
import type { HttpGeneratorConfig } from '../../role-config';
import { checkServedModel, loadOpenAiHttpGenerator } from './openai-http-generator';
import { modelfileCheck } from './served-model';

const pin = PROVISIONAL_DEFAULT_PINS.generator;
const OTHER = 'a'.repeat(64);
const blob = (sha256: string) => `/Users/ann/.ollama/models/blobs/sha256-${sha256}`;

/** The shape `ollama show --modelfile` prints, header comment included, by the Ollama `.claude/scripts/ollama-pin.sh` pins. */
const modelfile = (...directives: readonly string[]) =>
  [
    '# Modelfile generated by "ollama show"',
    '# To build a new Modelfile based on this, replace FROM with:',
    '# FROM qwen3-4b-q4_k_m-7485fe6f11af:latest',
    '',
    ...directives,
    'TEMPLATE {{ .Prompt }}',
  ].join('\n');

describe('modelfileCheck', () => {
  it('verifies a FROM blob named by the pin’s digest', () => {
    expect(modelfileCheck(modelfile(`FROM ${blob(pin.sha256)}`), pin)).toEqual({
      status: 'verified',
    });
  });

  it.each([
    ['CRLF line endings', `FROM ${blob(pin.sha256)}\r`],
    ['a longer keyword beside it', `FROM ${blob(pin.sha256)}\nFROMS ${blob(OTHER)}`],
    [
      'lowercase lines, which `ollama show` never prints as directives',
      `FROM ${blob(pin.sha256)}\nfrom ${blob(OTHER)}\nadapter ${blob(OTHER)}`,
    ],
    [
      'directive-like lines inside a multi-line value',
      [
        `FROM ${blob(pin.sha256)}`,
        'SYSTEM """Answer from the slides.',
        `FROM ${blob(OTHER)}`,
        `ADAPTER ${blob(OTHER)}`,
        'Adapter settings are not yours to change.',
        'From the slides only."""',
      ].join('\n'),
    ],
  ])('reads a FROM line written with %s', (_case, line) => {
    expect(modelfileCheck(modelfile(line), pin).status).toBe('verified');
  });

  it('refuses a blob the pin does not name, naming both digests', () => {
    expect(modelfileCheck(modelfile(`FROM ${blob(OTHER)}`), pin)).toEqual({
      status: 'mismatch',
      detail: `serves blob sha256-${OTHER}, not the pin's sha256-${pin.sha256}`,
    });
  });

  it.each([
    ['', []],
    [' after a one-line quoted value', ['SYSTEM """Answer from the slides."""']],
  ])('refuses an ADAPTER line beside the pinned weights%s', (_case, before) => {
    const check = modelfileCheck(
      modelfile(`FROM ${blob(pin.sha256)}`, ...before, `ADAPTER ${blob(OTHER)}`),
      pin,
    );
    expect(check).toEqual({
      status: 'mismatch',
      detail: `serves ADAPTER ${blob(OTHER)}, which the pin does not name`,
    });
  });

  it.each([
    ['no FROM line', modelfile(), 'the modelfile has 0 FROM lines, not one'],
    [
      'two FROM lines',
      modelfile(`FROM ${blob(pin.sha256)}`, `FROM ${blob(OTHER)}`),
      'the modelfile has 2 FROM lines, not one',
    ],
    [
      'a FROM naming a model, not a blob',
      modelfile('FROM qwen3:4b'),
      'FROM names no content-addressed blob: qwen3:4b',
    ],
    [
      'a sha256- file outside the blob store',
      modelfile(`FROM /Users/ann/models/sha256-${pin.sha256}`),
      `FROM names no content-addressed blob: /Users/ann/models/sha256-${pin.sha256}`,
    ],
    [
      'a blob name longer than a digest',
      modelfile(`FROM ${blob(pin.sha256)}0`),
      `FROM names no content-addressed blob: ${blob(pin.sha256)}0`,
    ],
  ])('leaves %s unverified', (_case, text, reason) => {
    expect(modelfileCheck(text, pin)).toEqual({ status: 'unverified', reason });
  });
});

type Handler = (request: IncomingMessage, body: string, response: ServerResponse) => void;

interface FixtureServer {
  readonly server: Server;
  readonly origin: string;
  handler: Handler;
}

const startServer = async (): Promise<FixtureServer> => {
  const fixture: { handler: Handler } = { handler: (_request, _body, response) => response.end() };
  const server = createServer((request, response) => {
    let body = '';
    request.on('data', (chunk: Buffer) => (body += chunk.toString()));
    request.on('end', () => {
      fixture.handler(request, body, response);
    });
  });
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
  const { port } = server.address() as AddressInfo;
  return Object.assign(fixture, { server, origin: `http://127.0.0.1:${String(port)}` });
};

const stopServer = async ({ server }: FixtureServer): Promise<void> => {
  server.closeAllConnections();
  await new Promise((resolve) => server.close(resolve));
};

const reply =
  (status: number, body: string, contentType = 'text/event-stream'): Handler =>
  (_request, _body, response) => {
    response.writeHead(status, { 'content-type': contentType }).end(body);
  };

let fixture: FixtureServer;
let config: HttpGeneratorConfig;

beforeEach(async () => {
  fixture = await startServer();
  config = {
    pin,
    endpoint: `${fixture.origin}/v1/`,
    servedModel: 'qwen3-4b-q4_k_m-7485fe6f11af',
    timeoutMs: 2000,
    sampling: { temperature: 0, seed: 0 },
  };
});

afterEach(async () => {
  await stopServer(fixture);
});

const json = (status: number, value: unknown): Handler =>
  reply(status, JSON.stringify(value), 'application/json');

describe('checkServedModel', () => {
  it('asks /api/show on the endpoint’s origin for the served model', async () => {
    const seen: { url?: string; method?: string; body?: unknown } = {};
    fixture.handler = (request, body, response) => {
      const parsed: unknown = JSON.parse(body);
      Object.assign(seen, { url: request.url, method: request.method, body: parsed });
      json(200, { modelfile: modelfile(`FROM ${blob(pin.sha256)}`) })(request, body, response);
    };
    await expect(checkServedModel(config)).resolves.toEqual({ status: 'verified' });
    expect(seen).toEqual({
      url: '/api/show',
      method: 'POST',
      body: { model: 'qwen3-4b-q4_k_m-7485fe6f11af' },
    });
  });

  it('names the server and the served model on a mismatch from the modelfile', async () => {
    fixture.handler = json(200, { modelfile: modelfile(`FROM ${blob(OTHER)}`) });
    const check = await checkServedModel(config);
    expect(check.status === 'mismatch' && check.detail).toBe(
      `POST ${new URL('/api/show', config.endpoint).href} for ${config.servedModel}: ` +
        `serves blob sha256-${OTHER}, not the pin's sha256-${pin.sha256}`,
    );
  });

  it('names the server and the served model on an unverified modelfile', async () => {
    fixture.handler = json(200, { modelfile: modelfile() });
    const check = await checkServedModel(config);
    expect(check.status === 'unverified' && check.reason).toBe(
      `POST ${new URL('/api/show', config.endpoint).href} for ${config.servedModel}: ` +
        'the modelfile has 0 FROM lines, not one',
    );
  });

  it.each<[string, Handler, RegExp]>([
    [
      'a server with no /api/show',
      (_request, _body, response) => response.writeHead(404).end('404 page not found'),
      /^POST http:\/\/127\.0\.0\.1:\d+\/api\/show for qwen3-4b-q4_k_m-7485fe6f11af: HTTP 404: 404 page not found$/,
    ],
    [
      'a body that is not JSON',
      (_request, _body, response) => response.writeHead(200).end('<html>'),
      /^POST .*\/api\/show for qwen3-4b-q4_k_m-7485fe6f11af: SyntaxError: /,
    ],
    [
      'JSON that is not an /api/show reply',
      json(200, { template: '{{ .Prompt }}' }),
      /^POST .*\/api\/show for qwen3-4b-q4_k_m-7485fe6f11af: not an \/api\/show reply: .*modelfile/s,
    ],
    [
      'a redirect, which is never followed',
      (_request, _body, response) => response.writeHead(302, { location: '/elsewhere' }).end(),
      /^POST .*\/api\/show for qwen3-4b-q4_k_m-7485fe6f11af: TypeError: /,
    ],
  ])('leaves %s unverified', async (_case, serve, reason) => {
    fixture.handler = (request, body, response) => {
      if (request.url === '/elsewhere')
        json(200, { modelfile: modelfile(`FROM ${blob(pin.sha256)}`) })(request, body, response);
      else serve(request, body, response);
    };
    const check = await checkServedModel(config);
    expect(check.status).toBe('unverified');
    expect(check.status === 'unverified' && check.reason).toMatch(reason);
  });

  it('leaves a server that does not answer within timeoutMs unverified', async () => {
    fixture.handler = () => undefined;
    const check = await checkServedModel({ ...config, timeoutMs: 50 });
    expect(check.status === 'unverified' && check.reason).toMatch(/TimeoutError/);
  });

  it('leaves a server that is not listening unverified', async () => {
    const check = await checkServedModel({ ...config, endpoint: 'http://127.0.0.1:9/v1/' });
    expect(check.status === 'unverified' && check.reason).toMatch(/fetch failed/);
  });
});

describe('loadOpenAiHttpGenerator', () => {
  const fromBlob = (sha256: string) => `FROM /Users/ann/.ollama/models/blobs/sha256-${sha256}\n`;
  const show = (status: number, value: unknown): Handler =>
    reply(status, JSON.stringify(value), 'application/json');

  it('loads a generator that carries the verified weights', async () => {
    fixture.handler = show(200, { modelfile: fromBlob(config.pin.sha256) });
    const load = await loadOpenAiHttpGenerator(config);
    expect(load.status === 'loaded' && load.generator.served).toEqual({ status: 'verified' });
  });

  it('loads a generator on a server it cannot ask, recording why', async () => {
    fixture.handler = reply(404, '404 page not found', 'text/plain');
    const load = await loadOpenAiHttpGenerator(config);
    const served = load.status === 'loaded' ? load.generator.served : null;
    expect(served?.status === 'unverified' && served.reason).toMatch(/HTTP 404/);
  });

  it('refuses a server that serves weights the pin does not name', async () => {
    fixture.handler = show(200, { modelfile: fromBlob('a'.repeat(64)) });
    const load = await loadOpenAiHttpGenerator(config);
    expect(load).toMatchObject({
      status: 'load-failed',
      role: 'generator',
      reason: 'served-mismatch',
    });
    expect(load.status === 'load-failed' && load.detail).toMatch(
      /^POST .*\/api\/show for qwen3-4b-q4_k_m-7485fe6f11af: serves blob sha256-a{64}, not the pin's/,
    );
  });

  it('refuses an endpoint off loopback before asking it anything', async () => {
    let asked = false;
    fixture.handler = (_incoming, _body, response) => {
      asked = true;
      response.end();
    };
    const endpoint = `${fixture.origin.replace('127.0.0.1', '0.0.0.0')}/v1/`;
    await expect(loadOpenAiHttpGenerator({ ...config, endpoint })).rejects.toThrow();
    expect(asked).toBe(false);
  });
});
