import { createServer, type IncomingMessage, type Server, type ServerResponse } from 'node:http';
import type { AddressInfo } from 'node:net';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { PROVISIONAL_DEFAULT_PINS } from '../../provisional-pins';
import type { HttpGeneratorConfig } from '../../role-config';
import { checkServedModel, modelfileCheck } from './served-model';

const pin = PROVISIONAL_DEFAULT_PINS.generator;
const OTHER = 'a'.repeat(64);
const blob = (sha256: string) => `/Users/ann/.ollama/models/blobs/sha256-${sha256}`;

/** The shape `ollama show --modelfile` prints, header comment included (Ollama 0.40.6). */
const modelfile = (...directives: readonly string[]) =>
  [
    '# Modelfile generated by "ollama show"',
    '# To build a new Modelfile based on this, replace FROM with:',
    '# FROM qwen3-4b-q4_k_m-7485fe6f11af:latest',
    '',
    ...directives,
    'TEMPLATE {{ .Prompt }}',
    'PARAMETER num_ctx 40960',
  ].join('\n');

describe('modelfileCheck', () => {
  it('verifies a FROM blob named by the pin’s digest', () => {
    expect(modelfileCheck(modelfile(`FROM ${blob(pin.sha256)}`), pin)).toEqual({
      status: 'verified',
    });
  });

  it.each([
    ['a lowercase keyword', `from ${blob(pin.sha256)}`],
    ['CRLF line endings', `FROM ${blob(pin.sha256)}\r`],
    ['a longer keyword beside it', `FROM ${blob(pin.sha256)}\nFROMS ${blob(OTHER)}`],
  ])('reads a FROM line written with %s', (_case, line) => {
    expect(modelfileCheck(modelfile(line), pin).status).toBe('verified');
  });

  it('refuses a blob the pin does not name, naming both digests', () => {
    expect(modelfileCheck(modelfile(`FROM ${blob(OTHER)}`), pin)).toEqual({
      status: 'mismatch',
      detail: `serves blob sha256-${OTHER}, not the pin's sha256-${pin.sha256}`,
    });
  });

  it.each(['ADAPTER', 'adapter'])('refuses an %s line beside the pinned weights', (keyword) => {
    const check = modelfileCheck(
      modelfile(`FROM ${blob(pin.sha256)}`, `${keyword} ${blob(OTHER)}`),
      pin,
    );
    expect(check).toEqual({
      status: 'mismatch',
      detail: `serves ADAPTER ${blob(OTHER)}, which the pin does not name`,
    });
  });

  it.each([
    ['no FROM line', modelfile(), 'the modelfile has 0 FROM lines, not one'],
    [
      'two FROM lines',
      modelfile(`FROM ${blob(pin.sha256)}`, `FROM ${blob(OTHER)}`),
      'the modelfile has 2 FROM lines, not one',
    ],
    [
      'a FROM naming a model, not a blob',
      modelfile('FROM qwen3:4b'),
      'FROM names no content-addressed blob: qwen3:4b',
    ],
    [
      'a sha256- file outside the blob store',
      modelfile(`FROM /Users/ann/models/sha256-${pin.sha256}`),
      `FROM names no content-addressed blob: /Users/ann/models/sha256-${pin.sha256}`,
    ],
    [
      'a blob name longer than a digest',
      modelfile(`FROM ${blob(pin.sha256)}0`),
      `FROM names no content-addressed blob: ${blob(pin.sha256)}0`,
    ],
  ])('leaves %s unverified', (_case, text, reason) => {
    expect(modelfileCheck(text, pin)).toEqual({ status: 'unverified', reason });
  });
});

type Handler = (request: IncomingMessage, body: string, response: ServerResponse) => void;

let server: Server;
let handler: Handler;
let config: HttpGeneratorConfig;

beforeEach(async () => {
  handler = (_request, _body, response) => response.end();
  server = createServer((request, response) => {
    let body = '';
    request.on('data', (chunk: Buffer) => (body += chunk.toString()));
    request.on('end', () => {
      handler(request, body, response);
    });
  });
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
  const { port } = server.address() as AddressInfo;
  config = {
    pin,
    endpoint: `http://127.0.0.1:${String(port)}/v1/`,
    servedModel: 'qwen3-4b-q4_k_m-7485fe6f11af',
    timeoutMs: 2000,
    sampling: { temperature: 0, seed: 0 },
  };
});

afterEach(async () => {
  server.closeAllConnections();
  await new Promise((resolve) => server.close(resolve));
});

const json =
  (status: number, value: unknown): Handler =>
  (_request, _body, response) => {
    response.writeHead(status, { 'content-type': 'application/json' }).end(JSON.stringify(value));
  };

describe('checkServedModel', () => {
  it('asks /api/show on the endpoint’s origin for the served model', async () => {
    const seen: { url?: string; method?: string; body?: unknown } = {};
    handler = (request, body, response) => {
      const parsed: unknown = JSON.parse(body);
      Object.assign(seen, { url: request.url, method: request.method, body: parsed });
      json(200, { modelfile: modelfile(`FROM ${blob(pin.sha256)}`) })(request, body, response);
    };
    await expect(checkServedModel(config)).resolves.toEqual({ status: 'verified' });
    expect(seen).toEqual({
      url: '/api/show',
      method: 'POST',
      body: { model: 'qwen3-4b-q4_k_m-7485fe6f11af' },
    });
  });

  it('carries a mismatch from the modelfile', async () => {
    handler = json(200, { modelfile: modelfile(`FROM ${blob(OTHER)}`) });
    await expect(checkServedModel(config)).resolves.toMatchObject({ status: 'mismatch' });
  });

  it.each<[string, Handler, RegExp]>([
    [
      'a server with no /api/show',
      (_request, _body, response) => response.writeHead(404).end('404 page not found'),
      /^POST http:\/\/127\.0\.0\.1:\d+\/api\/show: HTTP 404: 404 page not found$/,
    ],
    [
      'a body that is not JSON',
      (_request, _body, response) => response.writeHead(200).end('<html>'),
      /^POST .*\/api\/show: SyntaxError: /,
    ],
    [
      'JSON that is not an /api/show reply',
      json(200, { template: '{{ .Prompt }}' }),
      /^POST .*\/api\/show: not an \/api\/show reply: .*modelfile/s,
    ],
    [
      'a redirect, which is never followed',
      (_request, _body, response) => response.writeHead(302, { location: '/elsewhere' }).end(),
      /^POST .*\/api\/show: TypeError: /,
    ],
  ])('leaves %s unverified', async (_case, serve, reason) => {
    handler = (request, body, response) => {
      if (request.url === '/elsewhere')
        json(200, { modelfile: modelfile(`FROM ${blob(pin.sha256)}`) })(request, body, response);
      else serve(request, body, response);
    };
    const check = await checkServedModel(config);
    expect(check.status).toBe('unverified');
    expect(check.status === 'unverified' && check.reason).toMatch(reason);
  });

  it('leaves a server that does not answer within timeoutMs unverified', async () => {
    handler = () => undefined;
    const check = await checkServedModel({ ...config, timeoutMs: 50 });
    expect(check.status === 'unverified' && check.reason).toMatch(/TimeoutError/);
  });

  it('leaves a server that is not listening unverified', async () => {
    const check = await checkServedModel({ ...config, endpoint: 'http://127.0.0.1:9/v1/' });
    expect(check.status === 'unverified' && check.reason).toMatch(/fetch failed/);
  });
});
